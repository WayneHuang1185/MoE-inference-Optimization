def render_entropy(by_layer: dict, regime: str, title: str, out_path: Path, n_layers: int = 30) -> None:
    """Per-layer entropy panel (one line per candidate) + recall@8 mirror panel.

    Hypothesis: a good predictor should be self-confident — its softmax(logit)
    distribution is peaky (low entropy), close to the true peaky distribution.
    If true, lines that sit lower on the top panel should be higher on the
    bottom panel.
    """
    layers = list(range(0, n_layers - 1))
    candidates = [c for c, _ in CANDIDATES_ORDER]

    W = 1480
    panel_h = 380
    legend_h = 60
    H = 100 + legend_h + panel_h * 2 + 80

    plot_x0 = 80
    plot_w = W - 200

    svg = [f'<svg xmlns="http://www.w3.org/2000/svg" width="{W}" height="{H}" viewBox="0 0 {W} {H}">']
    svg.append(f'<rect x="0" y="0" width="{W}" height="{H}" fill="#ffffff"/>')
    svg.append(f'<text x="40" y="44" font-family="Arial, sans-serif" font-size="24" font-weight="700" fill="#222">{title}</text>')
    svg.append(f'<text x="40" y="70" font-family="Arial, sans-serif" font-size="13" fill="#555">{regime.upper()} regime. Top: H(softmax(pred_logits)) in nats per layer (lower = peakier = more confident); dashed black line = true_entropy reference. Bottom: per-token recall@8 (mirror, higher = better). Hypothesis: good predictors land on low pred_entropy AND high recall@8.</text>')

    lx0 = 80
    ly = 96
    per_row = 5
    item_w = 270
    for k, cand in enumerate(candidates):
        row = k // per_row
        col = k % per_row
        cx = lx0 + col * item_w
        cy = ly + row * 24
        color = LINE_COLORS.get(cand, "#444")
        label = next((lab for c, lab in CANDIDATES_ORDER if c == cand), cand)
        svg.append(f'<line x1="{cx}" y1="{cy + 6}" x2="{cx + 24}" y2="{cy + 6}" stroke="{color}" stroke-width="3"/>')
        svg.append(f'<circle cx="{cx + 12}" cy="{cy + 6}" r="3.5" fill="{color}"/>')
        svg.append(f'<text x="{cx + 32}" y="{cy + 10}" font-family="Arial, sans-serif" font-size="12" fill="#222">{label}</text>')

    panel_y_start = ly + 2 * 24 + 24

    # Auto y-range for entropy panel.
    log_n_experts = math.log(128)  # Gemma4 has 128 experts → max H = log(128) ≈ 4.852.
    ent_values = []
    for cand in candidates:
        for li in layers:
            d = by_layer.get((regime, cand, li), {})
            for k in ("pred_entropy_mean", "true_entropy_mean"):
                v = d.get(k, float("nan"))
                if not math.isnan(v) and not math.isinf(v):
                    ent_values.append(v)
    ent_max_raw = max(ent_values) if ent_values else log_n_experts
    ent_max = math.ceil(ent_max_raw * 4) / 4
    if ent_max <= 0:
        ent_max = log_n_experts
    ent_ticks = [ent_max * f for f in (0.0, 0.25, 0.5, 0.75, 1.0)]

    def draw_panel(y0: int, metric_key: str, panel_title: str, y_axis_label: str,
                   y_min: float, y_max: float, y_ticks, overlay_true: bool = False):
        plot_top = y0 + 40
        plot_bot = y0 + panel_h - 50
        plot_h = plot_bot - plot_top
        svg.append(f'<text x="40" y="{y0 + 24}" font-family="Arial, sans-serif" font-size="16" font-weight="700" fill="#222">{panel_title}</text>')
        svg.append(f'<rect x="{plot_x0}" y="{plot_top}" width="{plot_w}" height="{plot_h}" fill="#ffffff" stroke="#d0d7de" rx="4"/>')

        for v_tick in y_ticks:
            frac = (v_tick - y_min) / (y_max - y_min) if y_max > y_min else 0
            yy = plot_bot - frac * plot_h
            svg.append(f'<line x1="{plot_x0}" y1="{yy:.1f}" x2="{plot_x0 + plot_w}" y2="{yy:.1f}" stroke="#eef1f4"/>')
            svg.append(f'<text x="{plot_x0 - 8}" y="{yy + 4:.1f}" font-family="Arial, sans-serif" font-size="11" text-anchor="end" fill="#666">{v_tick:.2f}</text>')

        svg.append(f'<text x="36" y="{(plot_top + plot_bot)/2:.1f}" font-family="Arial, sans-serif" font-size="12" font-weight="700" text-anchor="middle" fill="#444" transform="rotate(-90, 36, {(plot_top + plot_bot)/2:.1f})">{y_axis_label}</text>')

        n_layers_data = len(layers)
        for li, layer_i in enumerate(layers):
            xf = (li + 0.5) / n_layers_data
            xx = plot_x0 + xf * plot_w
            if li % 2 == 0:
                svg.append(f'<text x="{xx:.1f}" y="{plot_bot + 16}" font-family="Arial, sans-serif" font-size="10" text-anchor="middle" fill="#555">{layer_i}</text>')
        svg.append(f'<text x="{plot_x0 + plot_w / 2:.1f}" y="{plot_bot + 36}" font-family="Arial, sans-serif" font-size="12" font-weight="700" text-anchor="middle" fill="#444">layer_i  (target = layer_i + 1)</text>')

        # true_entropy reference (computed from any candidate row at that layer
