METRIC_COLS = [
    ("router_logit_cos_mean_mean", "logit cos"),
    ("top1_match_mean",            "top1"),
    ("recall_at_8_mean",           "recall@8"),
    ("set_coverage_at_8_mean",     "cov@8"),
    ("set_coverage_at_16_mean",    "cov@16"),
    ("set_coverage_at_32_mean",    "cov@32"),
]


def parse_float(s: str) -> float:
    try:
        return float(s)
    except (TypeError, ValueError):
        return math.nan


def viridis_green(v: float) -> str:
    """Map v in [0, 1] to a green shade. Higher v → darker green."""
    if math.isnan(v):
        return "#e5e7eb"
    v = max(0.0, min(1.0, v))
    # Interpolate from #e8f0ef (pale) to #2d7a55 (dark green).
    pal = [
        (0.00, (232, 240, 239)),
        (0.30, (191, 218, 208)),
        (0.55, (123, 181, 157)),
        (0.75, (74, 154, 121)),
        (0.90, (58, 144, 107)),
        (1.00, (45, 122,  85)),
    ]
    for j in range(1, len(pal)):
        lo_v, lo = pal[j - 1]
        hi_v, hi = pal[j]
        if v <= hi_v:
            t = (v - lo_v) / (hi_v - lo_v) if hi_v > lo_v else 0.0
            r = int(lo[0] + t * (hi[0] - lo[0]))
            g = int(lo[1] + t * (hi[1] - lo[1]))
            b = int(lo[2] + t * (hi[2] - lo[2]))
            return f"#{r:02x}{g:02x}{b:02x}"
    return "#2d7a55"


def text_color_for(bg: str) -> str:
    if bg == "#e5e7eb":
        return "#666"
    r = int(bg[1:3], 16); g = int(bg[3:5], 16); b = int(bg[5:7], 16)
    luma = 0.299 * r + 0.587 * g + 0.114 * b
    return "#1f2328" if luma > 150 else "#ffffff"


def load_overall(csv_path: Path) -> dict:
    """Return {(regime, candidate): {metric: value}}."""
    out = {}
    with csv_path.open() as f:
        for row in csv.DictReader(f):
            key = (row.get("regime", "?"), row["candidate"])
            out[key] = {k: parse_float(v) for k, v in row.items() if k not in {"regime", "candidate", "source_node", "n_rows", "n_prompts", "n_layer_pairs"}}
            out[key]["n_rows"] = int(parse_float(row.get("n_rows", "0")) or 0)
    return out


def load_by_layer(csv_path: Path) -> dict:
    """Return {(regime, candidate, layer_i): {metric: value}}."""
    out = {}
    with csv_path.open() as f:
        for row in csv.DictReader(f):
            try:
                li = int(row["layer_i"])
            except (TypeError, ValueError):
                continue
            out[(row.get("regime", "?"), row["candidate"], li)] = {
                k: parse_float(v) for k, v in row.items()
                if k not in {"regime", "candidate", "layer_i", "target_layer", "n_prompts"}
            }
    return out


def render_overview(overall: dict, title: str, out_path: Path) -> None:
    # Layout
    W = 1480
    cell_w = 92
    label_w = 250
    metric_count = len(METRIC_COLS)
    row_h = 32
    table_w = label_w + cell_w * metric_count + 80           # left-margin + cells + rows-col
    panel_w = table_w + 40
    n_rows = len(CANDIDATES_ORDER)
    table_h = 60 + n_rows * row_h + 20
    H = 100 + table_h + 60 + table_h + 60

    svg = []
    svg.append(f'<svg xmlns="http://www.w3.org/2000/svg" width="{W}" height="{H}" viewBox="0 0 {W} {H}">')
    svg.append(f'<rect x="0" y="0" width="{W}" height="{H}" fill="#ffffff"/>')
    svg.append(f'<text x="40" y="44" font-family="Arial, sans-serif" font-size="24" font-weight="700" fill="#222">{title}</text>')
    svg.append(f'<text x="40" y="72" font-family="Arial, sans-serif" font-size="13" fill="#555">Per-candidate metrics in layer execution order; prefill batch and decode (1-token) regimes side-by-side. set_coverage = batch-level prefetch coverage of unique experts.</text>')

    def draw_table(y0: int, regime_title: str, regime_key: str, x0: int = 40):
        # Panel background
        svg.append(f'<text x="{x0 + 24}" y="{y0 + 22}" font-family="Arial, sans-serif" font-size="17" font-weight="700" fill="#222">{regime_title}</text>')
        svg.append(f'<rect x="{x0}" y="{y0 + 32}" width="{table_w}" height="{n_rows * row_h + 50}" fill="#ffffff" stroke="#d0d7de" rx="6"/>')
        # Column headers
        x_label = x0 + 16
        x_metric_start = x0 + label_w
        svg.append(f'<text x="{x_label}" y="{y0 + 62}" font-family="Arial, sans-serif" font-size="13" font-weight="700" fill="#333">candidate</text>')
        for j, (_col, name) in enumerate(METRIC_COLS):
            cx = x_metric_start + j * cell_w + cell_w / 2
            svg.append(f'<text x="{cx:.1f}" y="{y0 + 62}" font-family="Arial, sans-serif" font-size="12" font-weight="700" text-anchor="middle" fill="#333">{name}</text>')
        rows_x = x_metric_start + metric_count * cell_w + 40
        svg.append(f'<text x="{rows_x}" y="{y0 + 62}" font-family="Arial, sans-serif" font-size="12" font-weight="700" text-anchor="middle" fill="#333">rows</text>')
        svg.append(f'<line x1="{x0}" y1="{y0 + 70}" x2="{x0 + table_w}" y2="{y0 + 70}" stroke="#d0d7de"/>')

        # Rows
        for k, (cand, label) in enumerate(CANDIDATES_ORDER):
            ry = y0 + 78 + k * row_h
            if k % 2 == 0:
                svg.append(f'<rect x="{x0 + 1}" y="{ry - 18}" width="{table_w - 2}" height="{row_h}" fill="#fbfcfd"/>')
            data = overall.get((regime_key, cand), {})
            svg.append(f'<text x="{x_label}" y="{ry}" font-family="Arial, sans-serif" font-size="13" fill="#222">{label}</text>')
            for j, (col, _) in enumerate(METRIC_COLS):
                v = data.get(col, float("nan"))
                bg = viridis_green(v) if not math.isnan(v) else "#e5e7eb"
                fg = text_color_for(bg)
                cx = x_metric_start + j * cell_w
                svg.append(f'<rect x="{cx + 4}" y="{ry - 18}" width="{cell_w - 8}" height="{row_h - 6}" fill="{bg}" stroke="#e5e7eb" rx="4"/>')
                txt = "-" if math.isnan(v) else f"{v:.3f}"
                svg.append(f'<text x="{cx + cell_w / 2:.1f}" y="{ry}" font-family="Arial, sans-serif" font-size="13" font-weight="700" text-anchor="middle" fill="{fg}">{txt}</text>')
            rows_n = data.get("n_rows", 0)
            svg.append(f'<text x="{rows_x}" y="{ry}" font-family="Arial, sans-serif" font-size="12" text-anchor="middle" fill="#333">{int(rows_n) if rows_n else "-"}</text>')

    draw_table(96, "PREFILL  —  batch tokens > 1  (prefetch-coverage ceilinged by batch breadth)", "prefill")
    draw_table(96 + table_h + 40, "DECODE  —  1 token  (the regime where expert prefetch actually pays off)", "decode")

    svg.append("</svg>")
    out_path.write_text("\n".join(svg))


def render_layer(by_layer: dict, title: str, out_path: Path, n_layers: int = 30) -> None:
    layers = list(range(0, n_layers - 1))                       # layer_i values
    sources = [
        ("l_out", "#3a906b", "l_out (1 residual step ahead)"),
        ("attn_out", "#f59e42", "attn_out (1 FFN block ahead)"),
        ("layer_input_raw", "#5b8aff", "layer_input (full layer ahead)"),
    ]

    W = 1480
    panel_h = 320
    H = 100 + panel_h * 2 + 100

    bar_area_x = 80
    bar_area_w = W - 160
    bar_group_w = bar_area_w / len(layers)
    bar_w = bar_group_w / (len(sources) + 0.6)

    svg = [f'<svg xmlns="http://www.w3.org/2000/svg" width="{W}" height="{H}" viewBox="0 0 {W} {H}">']
    svg.append(f'<rect x="0" y="0" width="{W}" height="{H}" fill="#ffffff"/>')
    svg.append(f'<text x="40" y="44" font-family="Arial, sans-serif" font-size="24" font-weight="700" fill="#222">{title}</text>')
    svg.append(f'<text x="40" y="70" font-family="Arial, sans-serif" font-size="13" fill="#555">Per-layer prefetch coverage and per-token recall@8, decode regime. Higher = more of the layer i+1 expert set predictable from layer-i state.</text>')

    # Legend
    lx, ly = 80, 90
    for k, (_, color, name) in enumerate(sources):
        svg.append(f'<rect x="{lx + k*280}" y="{ly}" width="14" height="14" fill="{color}" rx="3"/>')
        svg.append(f'<text x="{lx + k*280 + 22}" y="{ly + 12}" font-family="Arial, sans-serif" font-size="13" fill="#222">{name}</text>')

    def draw_panel(y0: int, metric_key: str, panel_title: str, y_axis_label: str):
        svg.append(f'<text x="40" y="{y0 + 24}" font-family="Arial, sans-serif" font-size="16" font-weight="700" fill="#222">{panel_title}</text>')
        # Box
        plot_top = y0 + 40
        plot_bot = y0 + panel_h - 40
        plot_h = plot_bot - plot_top
        svg.append(f'<rect x="{bar_area_x}" y="{plot_top}" width="{bar_area_w}" height="{plot_h}" fill="#ffffff" stroke="#d0d7de" rx="4"/>')
        # Y-axis ticks (0, 0.25, 0.5, 0.75, 1.0)
        for v_tick in (0.0, 0.25, 0.5, 0.75, 1.0):
            yy = plot_bot - v_tick * plot_h
            svg.append(f'<line x1="{bar_area_x}" y1="{yy:.1f}" x2="{bar_area_x + bar_area_w}" y2="{yy:.1f}" stroke="#eef1f4"/>')
            svg.append(f'<text x="{bar_area_x - 8}" y="{yy + 4:.1f}" font-family="Arial, sans-serif" font-size="11" text-anchor="end" fill="#666">{v_tick:.2f}</text>')
        svg.append(f'<text x="40" y="{(plot_top + plot_bot)/2:.1f}" font-family="Arial, sans-serif" font-size="12" font-weight="700" text-anchor="middle" fill="#444" transform="rotate(-90, 40, {(plot_top + plot_bot)/2:.1f})">{y_axis_label}</text>')

        # Bars
        for li, layer_i in enumerate(layers):
            gx = bar_area_x + li * bar_group_w
            # X-axis tick label every 2 layers
            if li % 2 == 0:
                lab_x = gx + bar_group_w / 2
                svg.append(f'<text x="{lab_x:.1f}" y="{plot_bot + 16}" font-family="Arial, sans-serif" font-size="10" text-anchor="middle" fill="#555">{layer_i}</text>')
            for si, (src, color, _) in enumerate(sources):
                d = by_layer.get(("decode", src, layer_i), {})
                v = d.get(metric_key, float("nan"))
                if math.isnan(v):
                    continue
                v = max(0.0, min(1.0, v))
                bx = gx + 2 + si * bar_w
                bh = v * plot_h
                by_ = plot_bot - bh
                svg.append(f'<rect x="{bx:.1f}" y="{by_:.1f}" width="{bar_w - 1.5:.1f}" height="{bh:.1f}" fill="{color}" rx="1.5"/>')
        # X-axis title
        svg.append(f'<text x="{bar_area_x + bar_area_w / 2:.1f}" y="{plot_bot + 36}" font-family="Arial, sans-serif" font-size="12" font-weight="700" text-anchor="middle" fill="#444">layer_i  (target = layer_i + 1)</text>')

    draw_panel(120, "set_coverage_at_8_mean", "Decode — cov@8  (prefetch 8 experts, fraction of true unique experts covered)", "cov@8")
    draw_panel(120 + panel_h + 40, "recall_at_8_mean", "Decode — per-token recall@8", "recall@8")

    svg.append("</svg>")
    out_path.write_text("\n".join(svg))


# Distinct colors for ~10 candidate lines (Tab10-ish, accessible).
LINE_COLORS = {
    "layer_input_raw":        "#1f77b4",
    "attn_norm":              "#ff7f0e",
    "attn_out":               "#2ca02c",
    "ffn_norm_1_shared":      "#d62728",
    "ffn_mlp":                "#9467bd",
    "ffn_norm_2_moe":         "#8c564b",
    "ffn_moe":                "#e377c2",
    "ffn_moe_combined":       "#bcbd22",
    "l_out":                  "#17becf",
    "oracle_target_attn_out": "#888888",
}


def render_lines(by_layer: dict, regime: str, title: str, out_path: Path, n_layers: int = 30) -> None:
    """Two stacked line panels (cosine + recall@8), one line per candidate, decode regime."""
    layers = list(range(0, n_layers - 1))
    # Same ordering as the overview table — closest to target last.
    candidates = [c for c, _ in CANDIDATES_ORDER]

    W = 1480
    panel_h = 380
    legend_h = 60
    H = 100 + legend_h + panel_h * 2 + 80

    bar_area_x = 80
    bar_area_w = W - 200

    svg = [f'<svg xmlns="http://www.w3.org/2000/svg" width="{W}" height="{H}" viewBox="0 0 {W} {H}">']
    svg.append(f'<rect x="0" y="0" width="{W}" height="{H}" fill="#ffffff"/>')
    svg.append(f'<text x="40" y="44" font-family="Arial, sans-serif" font-size="24" font-weight="700" fill="#222">{title}</text>')
    svg.append(f'<text x="40" y="70" font-family="Arial, sans-serif" font-size="13" fill="#555">{regime.upper()} regime. One line per hidden-state candidate; x = layer_i (target = layer_i+1). Oracle is the upper-bound reference (= attn_out_{{i+1}} itself).</text>')

    # Legend (two rows if needed)
    lx0 = 80
    ly = 96
    per_row = 5
    item_w = 270
    for k, cand in enumerate(candidates):
        row = k // per_row
        col = k % per_row
        cx = lx0 + col * item_w
        cy = ly + row * 24
        color = LINE_COLORS.get(cand, "#444")
        label = next((lab for c, lab in CANDIDATES_ORDER if c == cand), cand)
        svg.append(f'<line x1="{cx}" y1="{cy + 6}" x2="{cx + 24}" y2="{cy + 6}" stroke="{color}" stroke-width="3"/>')
        svg.append(f'<circle cx="{cx + 12}" cy="{cy + 6}" r="3.5" fill="{color}"/>')
        svg.append(f'<text x="{cx + 32}" y="{cy + 10}" font-family="Arial, sans-serif" font-size="12" fill="#222">{label}</text>')

    panel_y_start = ly + 2 * 24 + 24

    def draw_panel(y0: int, metric_key: str, panel_title: str, y_axis_label: str,
                   y_min: float, y_max: float, y_ticks):
        plot_top = y0 + 40
        plot_bot = y0 + panel_h - 50
        plot_h = plot_bot - plot_top
        svg.append(f'<text x="40" y="{y0 + 24}" font-family="Arial, sans-serif" font-size="16" font-weight="700" fill="#222">{panel_title}</text>')
        svg.append(f'<rect x="{bar_area_x}" y="{plot_top}" width="{bar_area_w}" height="{plot_h}" fill="#ffffff" stroke="#d0d7de" rx="4"/>')

        # Y-axis grid + labels
        for v_tick in y_ticks:
            frac = (v_tick - y_min) / (y_max - y_min) if y_max > y_min else 0
            yy = plot_bot - frac * plot_h
            svg.append(f'<line x1="{bar_area_x}" y1="{yy:.1f}" x2="{bar_area_x + bar_area_w}" y2="{yy:.1f}" stroke="#eef1f4"/>')
            svg.append(f'<text x="{bar_area_x - 8}" y="{yy + 4:.1f}" font-family="Arial, sans-serif" font-size="11" text-anchor="end" fill="#666">{v_tick:.2f}</text>')
        # Zero line emphasized if 0 is in range
        if y_min < 0 < y_max:
            frac = (0 - y_min) / (y_max - y_min)
            yy = plot_bot - frac * plot_h
            svg.append(f'<line x1="{bar_area_x}" y1="{yy:.1f}" x2="{bar_area_x + bar_area_w}" y2="{yy:.1f}" stroke="#999"/>')

        svg.append(f'<text x="36" y="{(plot_top + plot_bot)/2:.1f}" font-family="Arial, sans-serif" font-size="12" font-weight="700" text-anchor="middle" fill="#444" transform="rotate(-90, 36, {(plot_top + plot_bot)/2:.1f})">{y_axis_label}</text>')

        # X-axis ticks
        n_layers_data = len(layers)
        for li, layer_i in enumerate(layers):
            xf = (li + 0.5) / n_layers_data
            xx = bar_area_x + xf * bar_area_w
            if li % 2 == 0:
                svg.append(f'<text x="{xx:.1f}" y="{plot_bot + 16}" font-family="Arial, sans-serif" font-size="10" text-anchor="middle" fill="#555">{layer_i}</text>')
        svg.append(f'<text x="{bar_area_x + bar_area_w / 2:.1f}" y="{plot_bot + 36}" font-family="Arial, sans-serif" font-size="12" font-weight="700" text-anchor="middle" fill="#444">layer_i  (target = layer_i + 1)</text>')

        # One polyline per candidate
        for cand in candidates:
            color = LINE_COLORS.get(cand, "#444")
            is_oracle = cand == "oracle_target_attn_out"
            pts = []
            for li, layer_i in enumerate(layers):
                d = by_layer.get((regime, cand, layer_i), {})
                v = d.get(metric_key, float("nan"))
                if math.isnan(v):
                    continue
                v_clamped = max(y_min, min(y_max, v))
                xf = (li + 0.5) / n_layers_data
                xx = bar_area_x + xf * bar_area_w
                frac = (v_clamped - y_min) / (y_max - y_min) if y_max > y_min else 0
                yy = plot_bot - frac * plot_h
                pts.append((xx, yy))
            if not pts:
                continue
            d_str = " ".join(f"{('M' if i == 0 else 'L')}{x:.1f},{y:.1f}" for i, (x, y) in enumerate(pts))
            dash = ' stroke-dasharray="6,4"' if is_oracle else ''
            opacity = 0.55 if is_oracle else 0.92
            svg.append(f'<path d="{d_str}" fill="none" stroke="{color}" stroke-width="2"{dash} opacity="{opacity}"/>')
            for x, y in pts:
                svg.append(f'<circle cx="{x:.1f}" cy="{y:.1f}" r="2.6" fill="{color}"/>')

    draw_panel(panel_y_start, "router_logit_cos_mean_mean",
               f"{regime.capitalize()} — router_logit_cos per layer (per-candidate)", "logit cos",
               -0.1, 1.0, [-0.1, 0.0, 0.25, 0.5, 0.75, 1.0])
    draw_panel(panel_y_start + panel_h + 20, "recall_at_8_mean",
               f"{regime.capitalize()} — recall@8 per layer (per-candidate)", "recall@8",
               0.0, 1.0, [0.0, 0.25, 0.5, 0.75, 1.0])

    svg.append("</svg>")
    out_path.write_text("\n".join(svg))


def render_kl_recall(by_layer: dict, regime: str, title: str, out_path: Path, n_layers: int = 30) -> None:
    """Independent figure: reverse KL (top) and recall@8 (bottom) per layer, decode regime.

    Reverse KL = KL(p_pred || p_true) — penalises predicted mass on experts the true
    distribution doesn't use; closer to the prefetch under-fetch cost than cos sim
    because softmax concentrates weight on the top-k experts.
    """
    layers = list(range(0, n_layers - 1))
    candidates = [c for c, _ in CANDIDATES_ORDER]

    W = 1480
    panel_h = 380
    legend_h = 60
    H = 100 + legend_h + panel_h * 2 + 80

    plot_x0 = 80
    plot_w = W - 200

    svg = [f'<svg xmlns="http://www.w3.org/2000/svg" width="{W}" height="{H}" viewBox="0 0 {W} {H}">']
    svg.append(f'<rect x="0" y="0" width="{W}" height="{H}" fill="#ffffff"/>')
    svg.append(f'<text x="40" y="44" font-family="Arial, sans-serif" font-size="24" font-weight="700" fill="#222">{title}</text>')
    svg.append(f'<text x="40" y="70" font-family="Arial, sans-serif" font-size="13" fill="#555">{regime.upper()} regime. Top panel: reverse KL = KL(softmax(pred_logits) ∥ softmax(true_logits)), lower is better. Bottom: per-token recall@8, higher is better.</text>')

    # Legend
    lx0 = 80
    ly = 96
    per_row = 5
    item_w = 270
    for k, cand in enumerate(candidates):
        row = k // per_row
        col = k % per_row
        cx = lx0 + col * item_w
        cy = ly + row * 24
        color = LINE_COLORS.get(cand, "#444")
        label = next((lab for c, lab in CANDIDATES_ORDER if c == cand), cand)
        svg.append(f'<line x1="{cx}" y1="{cy + 6}" x2="{cx + 24}" y2="{cy + 6}" stroke="{color}" stroke-width="3"/>')
        svg.append(f'<circle cx="{cx + 12}" cy="{cy + 6}" r="3.5" fill="{color}"/>')
        svg.append(f'<text x="{cx + 32}" y="{cy + 10}" font-family="Arial, sans-serif" font-size="12" fill="#222">{label}</text>')

    panel_y_start = ly + 2 * 24 + 24

    # Auto y-range for KL panel: take max across all (cand, layer) and round up.
    kl_values = []
    for cand in candidates:
        for li in layers:
            v = by_layer.get((regime, cand, li), {}).get("kl_rev_mean", float("nan"))
            if not math.isnan(v) and not math.isinf(v):
                kl_values.append(v)
    kl_max_raw = max(kl_values) if kl_values else 1.0
    # Round up to a nice number.
    kl_max = math.ceil(kl_max_raw * 4) / 4
    if kl_max <= 0:
        kl_max = 1.0
    kl_ticks = [kl_max * f for f in (0.0, 0.25, 0.5, 0.75, 1.0)]

    def draw_panel(y0: int, metric_key: str, panel_title: str, y_axis_label: str,
                   y_min: float, y_max: float, y_ticks, invert: bool = False):
        plot_top = y0 + 40
        plot_bot = y0 + panel_h - 50
        plot_h = plot_bot - plot_top
