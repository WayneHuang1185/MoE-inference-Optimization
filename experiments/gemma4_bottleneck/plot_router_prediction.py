        if overlay_true:
            true_pts = []
            for li, layer_i in enumerate(layers):
                v_true = float("nan")
                for cand in candidates:
                    d = by_layer.get((regime, cand, layer_i), {})
                    cand_v = d.get("true_entropy_mean", float("nan"))
                    if not math.isnan(cand_v):
                        v_true = cand_v
                        break
                if math.isnan(v_true) or math.isinf(v_true):
                    continue
                v_clamped = max(y_min, min(y_max, v_true))
                xf = (li + 0.5) / n_layers_data
                xx = plot_x0 + xf * plot_w
                frac = (v_clamped - y_min) / (y_max - y_min) if y_max > y_min else 0
                yy = plot_bot - frac * plot_h
