#!/usr/bin/env python3
"""Run a two-step runtime RPP hint-admission smoke test.

This is intentionally narrower than the final async prefetch design. The runner:

1. Generates the first token.
2. Runs the trained RPP model on prompt + first token.
3. Writes predicted experts to a simple hint file.
4. Runs matched continuation requests with and without GGML_MOE_RPP_HINTS.

The C++ backend admits hinted experts into the runtime GPU expert cache before
the true selected-expert demand path for that tensor. This validates the runtime
hint entry point, but it does not yet overlap H2D copies with GPU compute.
"""
