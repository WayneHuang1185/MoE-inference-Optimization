TENSOR_KINDS = ("gate", "up", "down")
LAYER_RE = re.compile(r"blk\.(\d+)\.ffn_(gate_up|gate|up|down)")


class TokenCache:
    def __init__(self, tokenizer_bin: Path, model_path: Path):
        self.tokenizer_bin = tokenizer_bin
        self.model_path = model_path
        self.cache: dict[str, list[int]] = {}

    def tokenize(self, text: str) -> list[int]:
        if text not in self.cache:
            self.cache[text] = tokenize_with_llama(self.tokenizer_bin, self.model_path, text)
        return self.cache[text]


def recover_first_token_ids(token_cache: TokenCache, prompt_text: str, first_text: str) -> tuple[list[int], list[int], dict[str, Any]]:
    prompt_ids = token_cache.tokenize(prompt_text)
    combined_ids = token_cache.tokenize(prompt_text + first_text)
    prefix_ok = combined_ids[: len(prompt_ids)] == prompt_ids
    if prefix_ok and len(combined_ids) > len(prompt_ids):
        first_token_id = int(combined_ids[len(prompt_ids)])
        return prompt_ids, prompt_ids + [first_token_id], {
            "prefix_ok": True,
            "prompt_tokens": len(prompt_ids),
            "combined_tokens": len(combined_ids),
            "first_token_id": first_token_id,
            "lcp_tokens": len(prompt_ids),
        }

    lcp = 0
    for a, b in zip(prompt_ids, combined_ids):
        if a != b:
            break
        lcp += 1
    if len(combined_ids) <= lcp:
        raise ValueError("cannot recover first generated token from first-token text")
    first_token_id = int(combined_ids[lcp])
    return prompt_ids, prompt_ids + [first_token_id], {
        "prefix_ok": False,
        "prompt_tokens": len(prompt_ids),
        "combined_tokens": len(combined_ids),
        "first_token_id": first_token_id,
        "lcp_tokens": lcp,
    }


def write_hint_file(path: Path, slots: list[tuple[int, int]]) -> dict[str, Any]:
    path.parent.mkdir(parents=True, exist_ok=True)
    lines: list[str] = [
        "# layer tensor_kind expert_id",
        "# generated by run_runtime_rpp_hint.py",
    ]
    for layer, expert in slots:
        for tensor_kind in TENSOR_KINDS:
            lines.append(f"{layer} {tensor_kind} {expert}")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return {
        "hint_path": str(path),
        "hint_slots": len(slots),
        "hint_lines": len(slots) * len(TENSOR_KINDS),
        "hint_tensor_kinds": list(TENSOR_KINDS),
    }


def iter_jsonl(path: Path):
    with path.open("r", encoding="utf-8") as fh:
        for line_no, line in enumerate(fh, start=1):
            if not line.strip():
                continue
            try:
                yield line_no, json.loads(line)
            except json.JSONDecodeError as exc:
                raise ValueError(f"{path}:{line_no}: invalid JSONL: {exc}") from exc


def trace_paths_from_results(paths: list[Path]) -> list[Path]:
    out: list[Path] = []
    seen: set[Path] = set()
    for result_path in paths:
        for _, obj in iter_jsonl(result_path):
            if obj.get("type") != "request":
                continue
            trace_path = obj.get("moe_trace_path")
            if not trace_path:
                continue
            resolved = Path(str(trace_path)).expanduser().resolve()
            if resolved not in seen:
                out.append(resolved)
                seen.add(resolved)
    return out


def load_frequency_counts(result_paths: list[Path]) -> dict[int, Counter[int]]:
    counts: dict[int, Counter[int]] = defaultdict(Counter)
    trace_paths = trace_paths_from_results(result_paths)
    for trace_path in trace_paths:
        if not trace_path.exists():
            continue
        for _, event in iter_jsonl(trace_path):
            if event.get("event") != "moe_selected_expert_copy":
                continue
            input_name = str(event.get("input_name", ""))
            match = LAYER_RE.search(input_name)
            if not match:
                continue
            layer = int(match.group(1))
            tensor_kind = match.group(2)
            if tensor_kind not in {"gate", "gate_up"}:
                continue
            for expert in event.get("selected_ids", []):
                counts[layer][int(expert)] += 1
    return counts


def predict_ranked_experts(bundle, token_ids: list[int], top_k: int) -> tuple[dict[int, list[int]], float, dict[str, Any]]:
    max_seq_len = int(bundle.config["max_seq_len"])
    crop_start = max(0, len(token_ids) - max_seq_len)
    cropped = token_ids[crop_start:]
    ids = torch.tensor([cropped], dtype=torch.long, device=bundle.device)
    attention_mask = torch.ones_like(ids, dtype=torch.bool, device=bundle.device)

    t0 = time.time()
    with torch.inference_mode():
        logits = bundle.model(ids, attention_mask=attention_mask)
        top = torch.topk(logits[0, -1, :, :], k=int(top_k), dim=-1).indices.cpu()
    forward_s = time.time() - t0

    ranked = {
        int(layer): [int(expert) for expert in top[layer].tolist()]
        for layer in range(top.shape[0])
    }
    return ranked, forward_s, {
        "input_tokens": len(token_ids),
        "cropped_tokens": len(cropped),
        "crop_start": crop_start,
        "top_k": int(top_k),
        "logits_shape": list(logits.shape),
    }


def select_hint_slots(
    ranked: dict[int, list[int]],
    *,
    policy: str,
    top_k: int,
    admit_per_layer: int,
    frequency_counts: dict[int, Counter[int]],
    frequency_top_per_layer: int,
) -> list[tuple[int, int]]:
    slots: list[tuple[int, int]] = []
    for layer in sorted(ranked):
        candidates = ranked[layer][:top_k]
        if policy == "rank":
            selected = candidates
        elif policy == "fto":
            freq = frequency_counts.get(layer, Counter())
            if frequency_top_per_layer > 0:
                frequent = {expert for expert, _ in freq.most_common(frequency_top_per_layer)}
                candidates = [expert for expert in candidates if expert in frequent]
            scored = [
                (int(freq.get(expert, 0)), -rank, expert)
                for rank, expert in enumerate(candidates)
                if int(freq.get(expert, 0)) > 0
            ]
            scored.sort(reverse=True)
            keep = admit_per_layer if admit_per_layer > 0 else max(1, min(2, top_k))
            selected = [expert for _, _, expert in scored[:keep]]
        else:
            raise ValueError(f"unknown policy: {policy}")

        for expert in selected:
            slots.append((layer, int(expert)))
    return sorted(set(slots))


def run_server_request(
    *,
    config: dict[str, Any],
    server_bin: Path,
    model: Path,
    prompt_text: str,
    n_predict: int,
    output_stem: str,
    log_path: Path,
    trace_path: Path,
    op_offload_min_batch: int,
    moe_expert_cache_mb: int | None,
    rpp_hints_path: Path | None,
    wait_timeout_s: float,
    request_timeout_s: float,
    trace_detail: str,
    keep_cache: bool,
) -> tuple[dict[str, Any], dict[str, Any], str]:
    proc: subprocess.Popen | None = None
    if not keep_cache:
        evict_file_pages(model)

    try:
        proc = start_server(
            server_bin=server_bin,
            model=model,
            host=str(config["host"]),
            port=int(config["port"]),
            ctx=int(config["ctx"]),
            threads=int(config["threads"]),
            ngl=int(config["ngl_gpu"]),
            log_path=log_path,
            trace_path=trace_path,
            trace_detail=trace_detail,
            op_offload_min_batch=op_offload_min_batch,
            moe_expert_cache_mb=moe_expert_cache_mb,
            rpp_hints_path=rpp_hints_path,
        )
        wait_for_server(str(config["host"]), int(config["port"]), timeout_s=wait_timeout_s, proc=proc)

        min0, maj0 = proc_faults(proc.pid)
        rss0 = proc_rss_kb(proc.pid)
        io0 = proc_io(proc.pid)
        mem0 = meminfo()
        started = time.time()
        result = run_completion(
            host=str(config["host"]),
            port=int(config["port"]),
            prompt=prompt_text,
            n_predict=n_predict,
            temperature=float(config["temperature"]),
            timeout_s=request_timeout_s,
        )
        error = ""
    except (urllib.error.URLError, TimeoutError, OSError, RuntimeError) as exc:
        started = time.time()
        min0, maj0 = (0, 0)
        rss0 = 0
        io0 = {}
        mem0 = {}
        result = {
            "ttft_s": math.nan,
            "total_s": math.nan,
            "stream_chunks": 0,
            "tokens_per_s": 0.0,
            "content_preview": "",
        }
        error = str(exc)
    finally:
        if proc is not None:
            min1, maj1 = proc_faults(proc.pid)
            rss1 = proc_rss_kb(proc.pid)
            io1 = proc_io(proc.pid)
            mem1 = meminfo()
            pid = proc.pid
            stop_server(proc)
        else:
            min1, maj1 = (0, 0)
            rss1 = 0
            io1 = {}
            mem1 = {}
            pid = 0

    proc_stats = {
        "started_at": started,
        "pid": pid,
        "minor_faults": min1 - min0,
        "major_faults": maj1 - maj0,
        "rss_before_kb": rss0,
        "rss_after_kb": rss1,
        "rss_delta_kb": rss1 - rss0,
        "read_bytes_delta": int(io1.get("read_bytes", 0)) - int(io0.get("read_bytes", 0)),
        "rchar_delta": int(io1.get("rchar", 0)) - int(io0.get("rchar", 0)),
        "swap_free_delta_kb": int(mem1.get("swapfree_kb", 0)) - int(mem0.get("swapfree_kb", 0)),
        "swap_cached_delta_kb": int(mem1.get("swapcached_kb", 0)) - int(mem0.get("swapcached_kb", 0)),
        "mem_available_delta_kb": int(mem1.get("memavailable_kb", 0)) - int(mem0.get("memavailable_kb", 0)),
        "cached_delta_kb": int(mem1.get("cached_kb", 0)) - int(mem0.get("cached_kb", 0)),
        "log_path": str(log_path),
        "trace_path": str(trace_path),
        "output_stem": output_stem,
        "error": error,
    }
    return result, proc_stats, error


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser()
    parser.add_argument("--config", default="local_config.json")
    parser.add_argument("--rpp-config", default="../RPP/analyze/local_config.json")
    parser.add_argument("--tokenizer-bin", default="/home/hazcashi/lab/llama.cpp/build/bin/llama-tokenize")
    parser.add_argument("--max-prompts", type=int, default=1)
    parser.add_argument("--repeat", type=int, default=1)
    parser.add_argument("--top-k", type=int, default=8)
    parser.add_argument("--policy", choices=["rank", "fto"], default="rank")
    parser.add_argument("--admit-per-layer", type=int, default=0, help="For --policy fto, admit at most this many hinted experts per layer. Default keeps min(2, top-k).")
    parser.add_argument("--frequency-result", action="append", default=[], help="Result JSONL used to build per-layer expert frequency for FTO.")
    parser.add_argument("--frequency-top-per-layer", type=int, default=64, help="For --policy fto, only admit candidates within each layer's top-N frequent experts. Use 0 to disable.")
    parser.add_argument("--moe-expert-cache-mb", type=int, default=4096)
    parser.add_argument("--wait-timeout-s", type=float, default=300)
    parser.add_argument("--request-timeout-s", type=float, default=900)
    parser.add_argument("--output-prefix", default="phase5_runtime_rpp_hint_smoke")
    parser.add_argument("--op-offload-min-batch", type=int, default=None)
    parser.add_argument("--trace-detail", choices=["large", "all"], default="large")
    parser.add_argument("--keep-cache", action="store_true")
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    config_path = resolve_path(HERE, args.config)
    config = load_json(config_path)
    rpp_config_path = resolve_path(HERE, args.rpp_config)
    rpp_config = load_json(rpp_config_path)

    server_bin = resolve_path(config_path.parent, str(config["llama_server"]))
    model = resolve_path(config_path.parent, str(config["model"]))
    prompts_path = resolve_path(config_path.parent, str(config["prompts"]))
    out_dir = resolve_path(config_path.parent, str(config["out_dir"]))
    tokenizer_bin = resolve_path(config_path.parent, args.tokenizer_bin)
    rpp_checkpoint = resolve_path(rpp_config_path.parent, str(rpp_config["rpp_checkpoint"]))
    frequency_results = [resolve_path(config_path.parent, value) for value in args.frequency_result]
    out_dir.mkdir(parents=True, exist_ok=True)

    if not server_bin.exists():
        raise FileNotFoundError(server_bin)
    if not model.exists():
        raise FileNotFoundError(model)
    if not tokenizer_bin.exists():
        raise FileNotFoundError(tokenizer_bin)
    if not rpp_checkpoint.exists():
        raise FileNotFoundError(rpp_checkpoint)

    prompts = load_prompts(prompts_path, max_prompts=args.max_prompts)
    repeat = max(1, int(args.repeat))
    op_offload_min_batch = args.op_offload_min_batch
    if op_offload_min_batch is None:
        op_offload_min_batch = int(config.get("op_offload_min_batch", 1))

    result_path = out_dir / f"{args.output_prefix}_{time.strftime('%Y%m%d_%H%M%S')}.jsonl"
    token_cache = TokenCache(tokenizer_bin, model)
    rpp_bundle = load_rpp_bundle(rpp_checkpoint, device_name="cpu")
    frequency_counts: dict[int, Counter[int]] = {}
    if args.policy == "fto":
        if not frequency_results:
            raise ValueError("--policy fto requires at least one --frequency-result")
        print(f"[prep] loading FTO frequency from {len(frequency_results)} result file(s)", flush=True)
        frequency_counts = load_frequency_counts(frequency_results)
        if not frequency_counts:
            raise ValueError("FTO frequency table is empty")
        total_freq = sum(sum(counter.values()) for counter in frequency_counts.values())
        print(f"[prep] FTO frequency layers={len(frequency_counts)} selected-counts={total_freq}", flush=True)

    append_jsonl(result_path, {
        "type": "run_config",
        "phase": "phase5-runtime-rpp-hint-admission",
        "config_path": str(config_path),
        "rpp_config_path": str(rpp_config_path),
        "server_bin": str(server_bin),
        "model": str(model),
        "tokenizer_bin": str(tokenizer_bin),
        "rpp_checkpoint": str(rpp_checkpoint),
        "prompts": str(prompts_path),
        "prompt_count": len(prompts),
        "repeat": repeat,
        "top_k": int(args.top_k),
        "policy": str(args.policy),
        "admit_per_layer": int(args.admit_per_layer),
        "frequency_results": [str(path) for path in frequency_results],
        "frequency_top_per_layer": int(args.frequency_top_per_layer),
        "moe_expert_cache_mb": int(args.moe_expert_cache_mb),
        "op_offload_min_batch": op_offload_min_batch,
        "note": "Two-step runtime RPP hint admission. This is not async prefetch/overlap yet.",
    })

    total_requests = len(prompts) * repeat * 2
    logical_index = 0
    for rep in range(1, repeat + 1):
        for prompt in prompts:
            prompt_id = str(prompt["prompt_id"])
            safe_prompt_id = re.sub(r"[^A-Za-z0-9_.-]+", "_", prompt_id)
            print(f"[prep] prompt={prompt_id} repeat={rep}: first-token request", flush=True)

            first_stem = f"{result_path.stem}_{safe_prompt_id}_r{rep}_first"
            first_result, first_stats, first_error = run_server_request(
                config=config,
                server_bin=server_bin,
                model=model,
                prompt_text=str(prompt["prompt_text"]),
                n_predict=1,
                output_stem=first_stem,
                log_path=out_dir / "logs" / f"{first_stem}.server.log",
                trace_path=out_dir / "traces" / f"{first_stem}.trace.jsonl",
                op_offload_min_batch=op_offload_min_batch,
                moe_expert_cache_mb=0,
                rpp_hints_path=None,
                wait_timeout_s=float(args.wait_timeout_s),
                request_timeout_s=float(args.request_timeout_s),
                trace_detail=str(args.trace_detail),
                keep_cache=bool(args.keep_cache),
            )
            if first_error:
                raise RuntimeError(f"first-token request failed for {prompt_id}: {first_error}")
            first_text = str(first_result.get("content_preview", ""))
            if not first_text:
                raise RuntimeError(f"first-token request produced empty text for {prompt_id}")

            prompt_ids, rpp_ids, token_meta = recover_first_token_ids(token_cache, str(prompt["prompt_text"]), first_text)
            ranked, forward_s, prediction = predict_ranked_experts(rpp_bundle, rpp_ids, int(args.top_k))
            hint_slots = select_hint_slots(
                ranked,
                policy=str(args.policy),
                top_k=int(args.top_k),
                admit_per_layer=int(args.admit_per_layer),
                frequency_counts=frequency_counts,
                frequency_top_per_layer=int(args.frequency_top_per_layer),
            )
            policy_suffix = str(args.policy)
            if args.policy == "fto":
                keep = int(args.admit_per_layer) if int(args.admit_per_layer) > 0 else max(1, min(2, int(args.top_k)))
                policy_suffix += f"_admit{keep}_freq{int(args.frequency_top_per_layer)}"
            hint_path = out_dir / "rpp_hints" / f"{result_path.stem}_{safe_prompt_id}_r{rep}_top{args.top_k}_{policy_suffix}.hints.txt"
            hint_meta = write_hint_file(hint_path, hint_slots)
            continuation_prompt = str(prompt["prompt_text"]) + first_text
            print(
                f"[prep] prompt={prompt_id}: first_token={token_meta['first_token_id']} "
                f"rpp={forward_s * 1000:.1f}ms policy={args.policy} slots={hint_meta['hint_slots']} "
                f"hints={hint_path.name}",
                flush=True,
            )

            for label, hints_path in [
                ("demand-only", None),
                (f"real-rpp-{policy_suffix}-top{args.top_k}", hint_path),
            ]:
                logical_index += 1
                progress = f"[{logical_index:03d}/{total_requests:03d}]"
                scenario = f"phase5-two-step-{label}-runtime-cache-{args.moe_expert_cache_mb}mb"
                cont_stem = f"{result_path.stem}_{safe_prompt_id}_r{rep}_{label}"
                print(f"{progress} running {scenario} prompt={prompt_id}", flush=True)
                result, proc_stats, error = run_server_request(
                    config=config,
                    server_bin=server_bin,
                    model=model,
                    prompt_text=continuation_prompt,
                    n_predict=int(config["n_predict"]),
                    output_stem=cont_stem,
                    log_path=out_dir / "logs" / f"{cont_stem}.server.log",
                    trace_path=out_dir / "traces" / f"{cont_stem}.trace.jsonl",
                    op_offload_min_batch=op_offload_min_batch,
                    moe_expert_cache_mb=int(args.moe_expert_cache_mb),
                    rpp_hints_path=hints_path,
                    wait_timeout_s=float(args.wait_timeout_s),
                    request_timeout_s=float(args.request_timeout_s),
                    trace_detail=str(args.trace_detail),
                    keep_cache=bool(args.keep_cache),
                )
                trace_summary = parse_trace(Path(proc_stats["trace_path"]))
                record = {
                    "type": "request",
                    "phase": "phase5-runtime-rpp-hint-admission",
                    "scenario": scenario,
                    "request_index": logical_index,
                    "request_total": total_requests,
                    "repeat": rep,
                    "prompt_id": prompt_id,
                    "task_type": prompt["task_type"],
                    "source": prompt["source"],
                    "ngl": int(config["ngl_gpu"]),
                    "cpu_moe": True,
                    "op_offload": True,
                    "op_offload_min_batch": op_offload_min_batch,
                    "moe_expert_cache_mb": int(args.moe_expert_cache_mb),
                    "rpp_hints": str(hints_path) if hints_path is not None else None,
                    "top_k": int(args.top_k) if hints_path is not None else 0,
                    "rpp_policy": str(args.policy) if hints_path is not None else "none",
                    "admit_per_layer": int(args.admit_per_layer) if hints_path is not None else 0,
                    "frequency_top_per_layer": int(args.frequency_top_per_layer) if hints_path is not None else 0,
                    "first_token_text": first_text,
                    "first_token_s": float(first_result["total_s"]),
                    "rpp_forward_s": float(forward_s),
                    "rpp_input_tokens": int(prediction["input_tokens"]),
                    "rpp_cropped_tokens": int(prediction["cropped_tokens"]),
                    **token_meta,
                    **hint_meta,
                    "ctx": int(config["ctx"]),
                    "threads": int(config["threads"]),
                    "n_predict": int(config["n_predict"]),
                    "temperature": float(config["temperature"]),
                    **proc_stats,
                    **result,
                    **trace_summary,
                }
                record["error"] = error
                append_jsonl(result_path, record)
                print(
                    f"{progress} done {label} total={record['total_s']:.2f}s "
                    f"tok/s={record['tokens_per_s']:.2f} "
                    f"demand_h2d={record.get('moe_trace_payload_bytes', 0) / 1e6:.1f}MB "
                    f"rpp_hint_h2d={record.get('rpp_hint_h2d_payload_bytes', 0) / 1e6:.1f}MB "
                    f"total_h2d={record.get('runtime_total_h2d_payload_bytes', 0) / 1e6:.1f}MB "
                    f"cache_hit={record.get('moe_expert_cache_hit_rate', 0) * 100:.1f}%",
                    flush=True,
                )

    csv_path, md_path = write_summary(result_path)
    print(f"wrote {result_path}", flush=True)
    print(f"wrote {csv_path}", flush=True)
    print(f"wrote {md_path}", flush=True)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
